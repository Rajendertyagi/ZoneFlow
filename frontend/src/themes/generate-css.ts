/// <reference types="node" />
/**
 * Build-time generator: built-in JSON fixtures -> complete static CSS.
 *
 * Run with `bun run themes:generate` (write) or `bun run themes:check`
 * (verify the committed output is current). Bun is a build tool only; nothing
 * here ships to the browser or runs in production.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_PRESET_ID, PRESET_MANIFEST } from './manifest';
import type { ThemeTokenMap } from './schema';

export const GENERATED_CSS_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  'generated',
  'presets.css',
);

const HEADER = [
  '/* Generated by src/themes/generate-css.ts from src/themes/presets/*.json.',
  '   Do not edit by hand. Run `bun run themes:generate` to refresh. */',
].join('\n');

function tokenBlock(selector: string, tokens: ThemeTokenMap): string {
  const lines = Object.entries(tokens).map(([key, value]) => `  --${key}: ${value};`);
  // Distinct internal names let app.css map Tailwind's `--radius` /
  // `--font-sans` / `--font-mono` tokens to preset values without a
  // self-referential `var(--font-sans)` declaration.
  lines.push(`  --zf-radius: ${tokens.radius};`);
  lines.push(`  --zf-font-sans: ${tokens['font-sans']};`);
  lines.push(`  --zf-font-mono: ${tokens['font-mono']};`);
  return `${selector} {\n${lines.join('\n')}\n}`;
}

/**
 * Emit the full stylesheet. The `:root` / `:root.dark` blocks are the explicit
 * default-preset selection so the app renders correctly before WP2 installs the
 * pre-paint `data-theme` bootstrap. Per-preset blocks always win by specificity.
 */
export function generateCss(): string {
  const defaultEntry =
    PRESET_MANIFEST.find((item) => item.id === DEFAULT_PRESET_ID) ?? PRESET_MANIFEST[0];

  const blocks: string[] = [
    HEADER,
    tokenBlock(':root', defaultEntry.preset.light),
    tokenBlock(':root.dark', defaultEntry.preset.dark),
  ];

  for (const item of PRESET_MANIFEST) {
    blocks.push(tokenBlock(`:root[data-theme="${item.id}"]`, item.preset.light));
    blocks.push(tokenBlock(`:root[data-theme="${item.id}"].dark`, item.preset.dark));
  }

  return `${blocks.join('\n\n')}\n`;
}

/** Write the generated stylesheet to its committed location. */
export function writeGeneratedCss(): void {
  mkdirSync(dirname(GENERATED_CSS_PATH), { recursive: true });
  writeFileSync(GENERATED_CSS_PATH, generateCss(), 'utf8');
}

/** Fail when the committed stylesheet is stale relative to the fixtures. */
export function checkGeneratedCss(): boolean {
  const current = readFileSync(GENERATED_CSS_PATH, 'utf8');
  return current === generateCss();
}

const isMain = (import.meta as ImportMeta & { main?: boolean }).main === true;
if (isMain) {
  if (process.argv.includes('--check')) {
    if (checkGeneratedCss()) {
      console.log('themes: generated/presets.css is current.');
    } else {
      console.error('themes: generated/presets.css is stale. Run `bun run themes:generate`.');
      process.exitCode = 1;
    }
  } else {
    writeGeneratedCss();
    console.log(`themes: wrote ${GENERATED_CSS_PATH}`);
  }
}
